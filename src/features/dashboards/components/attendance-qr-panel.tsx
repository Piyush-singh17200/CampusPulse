"use client";

import { Check, Copy, LoaderCircle, QrCode } from "lucide-react";
import { useActionState, useState } from "react";

import { Button } from "@/components/ui/button";
import { ActionMessage } from "@/features/dashboards/components/action-form";
import { issueAttendanceQrAction } from "@/features/dashboards/actions";
import {
  initialDashboardActionState,
  type DashboardActionState,
} from "@/features/dashboards/types";
import { formatDateTime } from "@/lib/format";

export function AttendanceQrPanel({
  registrationId,
  timezone,
  disabledReason,
}: {
  registrationId: string;
  timezone: string;
  disabledReason?: string | null;
}) {
  const [state, formAction, pending] = useActionState<DashboardActionState, FormData>(
    issueAttendanceQrAction,
    initialDashboardActionState,
  );
  const [copied, setCopied] = useState(false);
  const qr = state.data?.qr;

  async function copyCode() {
    if (!qr) return;

    try {
      await navigator.clipboard.writeText(qr.payload);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 2_000);
    } catch {
      setCopied(false);
    }
  }

  return (
    <div className="space-y-4">
      {disabledReason ? (
        <p className="rounded-lg border border-line bg-canvas/70 px-4 py-3 text-sm leading-6 text-muted">
          {disabledReason}
        </p>
      ) : (
        <form action={formAction} className="space-y-3">
          <input type="hidden" name="registrationId" value={registrationId} />
          <Button type="submit" variant="signal" size="md" disabled={pending}>
            {pending ? (
              <LoaderCircle aria-hidden="true" className="size-4 animate-spin" />
            ) : (
              <QrCode aria-hidden="true" className="size-4" />
            )}
            {pending ? "Generating QR…" : qr ? "Refresh attendance QR" : "Show attendance QR"}
          </Button>
          <p className="text-[11px] leading-5 text-muted">
            Each refresh rotates the code. The previous QR stops working immediately.
          </p>
          <ActionMessage state={state} />
        </form>
      )}

      {qr ? (
        <div className="rounded-xl border border-forest/20 bg-forest-soft/25 p-4">
          <div className="flex flex-col gap-4 sm:flex-row sm:items-start">
            {/* The data URL is generated by the authenticated server action. */}
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img
              src={qr.qrDataUrl}
              alt="Attendance QR code for this event registration"
              className="mx-auto size-56 rounded-lg border border-line bg-paper p-2 sm:mx-0"
              width={224}
              height={224}
            />
            <div className="min-w-0 flex-1 space-y-3">
              <div>
                <p className="text-[10px] font-bold uppercase tracking-[0.14em] text-forest">
                  QR ready
                </p>
                <p className="mt-1 text-sm font-semibold leading-6 text-ink">
                  Show this code to an authorized organizer at the event entrance.
                </p>
                <p className="mt-1 text-xs leading-5 text-muted">
                  Valid until {formatDateTime(new Date(qr.expiresAt), timezone)}.
                </p>
              </div>

              <div className="rounded-lg border border-line bg-paper p-3">
                <p className="text-[10px] font-bold uppercase tracking-[0.14em] text-muted">
                  Manual fallback code
                </p>
                <code className="mt-2 block break-all font-mono text-[10px] leading-5 text-ink-soft">
                  {qr.payload}
                </code>
                <button
                  type="button"
                  onClick={copyCode}
                  className="mt-2 inline-flex items-center gap-1.5 text-[11px] font-bold text-forest underline decoration-forest/30 underline-offset-2 hover:decoration-forest focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-forest"
                >
                  {copied ? (
                    <Check aria-hidden="true" className="size-3.5" />
                  ) : (
                    <Copy aria-hidden="true" className="size-3.5" />
                  )}
                  {copied ? "Copied" : "Copy manual code"}
                </button>
              </div>

              <p className="text-[11px] leading-5 text-muted">
                If the QR image cannot load, show the manual code to an organizer. They can also
                look up your registration by name and roll number from the attendance list.
              </p>
            </div>
          </div>
        </div>
      ) : null}
    </div>
  );
}
